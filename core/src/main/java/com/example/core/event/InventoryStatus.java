package com.example.core.event;

public enum InventoryStatus {

    /**
     * Товар активен и доступен для продажи/заказа
     * - Виден в каталоге
     * - Можно добавлять в корзину
     * - Учитывается в остатках
     */
    ACTIVE,

    /**
     * Товар неактивен (временно скрыт)
     * - Не виден в каталоге
     * - Нельзя добавить в корзину
     * - Сохраняется в базе для истории
     * Использование: товар на редактировании, сезонный товар не в сезоне
     */
    INACTIVE,

    /**
     * Товар отсутствует на складе
     * - Виден в каталоге (но помечен как "нет в наличии")
     * - Нельзя добавить в корзину
     * - Ожидается пополнение
     * Использование: временно закончился, но будет поставка
     */
    OUT_OF_STOCK,

    /**
     * Товар снят с продажи (архив)
     * - Не виден в каталоге
     * - Нельзя добавить в корзину
     * - Сохраняется для аналитики и истории заказов
     * Использование: товар больше не производится, устарел
     */
    DISCONTINUED

}
